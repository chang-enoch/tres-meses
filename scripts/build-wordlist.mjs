/**
 * Builds the Wordle guess dictionary into src/data/wordle-dict.ts.
 *
 *   node scripts/build-wordlist.mjs
 *
 * Source: the `an-array-of-english-words` dev dependency (~275k modern words,
 * inflections included).
 *
 * macOS ships /usr/share/dict/words, which looks like the obvious source and
 * is a trap: it's Webster's Second (1934), and it contains "proudly" and
 * "proudness" but not "proud" — plus no plurals or past tenses at all. Every
 * one of those gaps becomes a "Not in word list" rejection of a perfectly
 * ordinary guess, which reads as the game being broken.
 *
 * Words are packed into one flat string rather than a JSON array. Every entry
 * is exactly 5 characters, so the delimiters and quotes a JSON array would
 * spend (~2 bytes/word, ~25KB) buy nothing.
 *
 * Puzzle answers and inside jokes are NOT baked in here — the game unions them
 * in at runtime from puzzles.ts, so editing content never means rebuilding.
 */
import { writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname } from 'node:path'
import { createRequire } from 'node:module'

// The package ships as a bare .json file, which an ESM `import` would demand
// an import attribute for. createRequire sidesteps the whole question.
const require = createRequire(import.meta.url)
const allWords = require('an-array-of-english-words')

const OUT = fileURLToPath(new URL('../src/data/wordle-dict.ts', import.meta.url))

const five = [...new Set(allWords.filter((w) => /^[a-z]{5}$/.test(w)))]
  .map((w) => w.toUpperCase())
  .sort()

const packed = five.join('')

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(
  OUT,
  `// GENERATED by scripts/build-wordlist.mjs — do not edit by hand.\n` +
    `// ${five.length} five-letter words, concatenated. Unpacked in lib/dictionary.ts.\n` +
    `export const WORD_COUNT = ${five.length}\n` +
    `export const PACKED_WORDS =\n  '${packed}'\n`,
)

console.log(`words : ${five.length}`)
console.log(`packed: ${(packed.length / 1024).toFixed(1)} KB raw`)
